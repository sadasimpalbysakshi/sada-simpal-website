// Generates supabase/seed_products.sql from the product list in src/data/products.ts.
// Run:  node scripts/make-seed.mjs
import { build } from "esbuild";
import { writeFileSync, mkdtempSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { createRequire } from "node:module";

const out = join(mkdtempSync(join(tmpdir(), "seed-")), "p.cjs");
await build({
  entryPoints: ["src/data/products.ts"],
  bundle: true, platform: "node", format: "cjs", outfile: out,
  alias: { "@": "./src" },
  define: { "import.meta.env.BASE_URL": '"/"' },
  logLevel: "silent",
});
const { collections, products } = createRequire(import.meta.url)(out);

const q = (s) => `'${String(s ?? "").replace(/'/g, "''")}'`;
const arr = (a) => (a.length ? `array[${a.map(q).join(",")}]::text[]` : `'{}'::text[]`);
const rel = (p) => p.replace(/^\//, ""); // "/products/x.webp" -> "products/x.webp"

let sql = `-- Generated by scripts/make-seed.mjs — loads your starting products.
-- Run AFTER schema_v2.sql. Safe to re-run (it updates by slug).

`;
collections.forEach((c, i) => {
  sql += `insert into public.categories (slug, name, description, image, sort_order) values (${q(c.slug)}, ${q(c.name)}, ${q(c.description)}, ${q(rel(c.image))}, ${i})
  on conflict (slug) do update set name = excluded.name, description = excluded.description, image = excluded.image, sort_order = excluded.sort_order;\n`;
});
sql += "\n";
products.forEach((p, i) => {
  sql += `insert into public.products (slug, name, short_description, description, category_slug, images, compare_at_price, material, care, features, is_bestseller, is_new, sort_order, created_at)
values (${q(p.id)}, ${q(p.name)}, ${q(p.shortDescription)}, ${q(p.description)}, ${q(p.category)}, ${arr(p.images.map(rel))}, ${p.originalPrice ?? "null"}, ${q(p.material)}, ${arr(p.care)}, ${arr(p.features)}, ${!!p.isBestseller}, ${!!p.isNewArrival}, ${i}, ${q(p.createdAt ?? "2026-01-01")})
on conflict (slug) do update set name = excluded.name, short_description = excluded.short_description, description = excluded.description, category_slug = excluded.category_slug, images = excluded.images, material = excluded.material, care = excluded.care, features = excluded.features;\n`;
  const sizes = p.sizes.length ? p.sizes : ["One Size"];
  const colors = p.colors.length ? p.colors : [{ name: "", hex: "" }];
  let n = 0;
  for (const s of sizes) for (const c of colors) {
    sql += `insert into public.product_variants (product_id, size, color, color_hex, price, stock, made_to_order, sort_order)
select id, ${q(s)}, ${q(c.name)}, ${q(c.hex)}, ${p.price}, 0, true, ${n++} from public.products where slug = ${q(p.id)}
on conflict (product_id, size, color) do nothing;\n`;
  }
});
writeFileSync("supabase/seed_products.sql", sql);
console.log(`seed: ${collections.length} categories, ${products.length} products`);
